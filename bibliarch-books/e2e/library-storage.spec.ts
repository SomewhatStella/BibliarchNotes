import {test,expect} from '@playwright/test';
import {answerAsk} from './ask';
import {seed,KEY} from '../src/model';
const readStored=()=>new Promise<string>((resolve,reject)=>{const r=indexedDB.open('bibliarch-books',1);r.onsuccess=()=>{const db=r.result;const q=db.transaction('library').objectStore('library').get('bibliarch-books-v1');q.onsuccess=()=>{resolve(q.result?.raw||'');db.close();};q.onerror=()=>reject(q.error);};r.onerror=()=>reject(r.error);});
test('legacy migration, large backup import, committed reload and failed-write draft backup',async({page})=>{
 const legacy=JSON.stringify(seed());
 await page.addInitScript(({key,raw})=>{if(!sessionStorage.getItem('seeded')){localStorage.setItem(key,raw);sessionStorage.setItem('seeded','1');}},{key:KEY,raw:legacy});
 await page.goto('/books');await expect(page.locator('.library-header').getByRole('status')).toBeVisible();
 expect(await page.evaluate(()=>localStorage.getItem('bibliarch-books-v1'))).toBe(legacy);
 const large=JSON.parse(legacy);large.books[0].title='Large durable library';
 const scene=large.books[0].chapters[0].scenes[0];
 for(let i=0;i<5;i++)large.books[0].chapters[0].scenes.push({...scene,id:'large-'+i,image:{src:'data:image/png;base64,'+'A'.repeat(1000000),alt:''}});
 const raw=JSON.stringify(large);expect(raw.length).toBeGreaterThan(4_000_000);
 await page.getByLabel('Import JSON backup').setInputFiles({name:'large.json',mimeType:'application/json',buffer:Buffer.from(raw)});
 await answerAsk(page);
 await expect(page.locator('.library-header').getByRole('status')).toBeVisible();
 await expect.poll(()=>page.evaluate(readStored)).toBe(raw);
 await page.reload();await expect(page.getByText('Large durable library',{exact:true}).first()).toBeVisible();
 expect(await page.evaluate(()=>localStorage.getItem('bibliarch-books-v1'))).toBe(legacy);
 await page.evaluate(()=>{const original=IDBObjectStore.prototype.put;(window as any).restorePut=()=>IDBObjectStore.prototype.put=original;IDBObjectStore.prototype.put=function(){throw new DOMException('Quota exceeded','QuotaExceededError');};});
 large.books[0].title='Unsaved entire draft';const unsaved=JSON.stringify(large);
 await page.getByLabel('Import JSON backup').setInputFiles({name:'unsaved.json',mimeType:'application/json',buffer:Buffer.from(unsaved)});
 await expect(page.locator('.error[role="alert"]')).toContainText('out of storage space');
 expect(await page.evaluate(readStored)).toBe(raw);
 const download=page.waitForEvent('download');await page.getByRole('button',{name:'Download a copy',exact:true}).click();const file=await (await download).path();
 const fs=await import('node:fs/promises');expect(JSON.parse(await fs.readFile(file!,'utf8'))).toEqual(large);
 await page.evaluate(()=>(window as any).restorePut());await page.getByRole('button',{name:'Try saving again'}).click();
 await expect.poll(()=>page.evaluate(readStored)).toBe(unsaved);
 await page.reload();await expect(page.getByText('Unsaved entire draft',{exact:true}).first()).toBeVisible();
});
