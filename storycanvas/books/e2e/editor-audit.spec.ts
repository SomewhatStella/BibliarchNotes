import {test,expect} from '@playwright/test';
test('find navigation, replace, selection styles and history are non-destructive',async({page})=>{
 await page.goto('/books');await page.getByRole('button',{name:'Create Japanese light novel',exact:true}).click();
 const editor=page.getByRole('textbox',{name:'Manuscript',exact:true}).first();await editor.click();
 await expect(page.getByRole('button',{name:'Undo',exact:true})).toBeDisabled();
 await editor.press('ControlOrMeta+a');await page.keyboard.type('hello hello');
 await expect(page.getByRole('button',{name:'Undo',exact:true})).toBeEnabled();
 await page.getByRole('textbox',{name:'Manuscript',exact:true}).nth(1).click();await editor.click();
 await expect(page.getByRole('button',{name:'Undo',exact:true})).toBeEnabled();
 await page.locator('summary[aria-label="Find & replace"]').click();await page.getByRole('textbox',{name:'Find text',exact:true}).fill('hello');
 await expect(page.getByRole('status').filter({hasText:'2 matches'})).toBeVisible();
 await expect(editor.locator('p')).toHaveText('hello hello');
 await page.getByRole('button',{name:'Next match',exact:true}).click();
 await expect.poll(()=>page.evaluate(()=>getSelection()?.toString())).toBe('hello');
 await page.getByLabel('Selection size',{exact:true}).selectOption('24px');
 await expect(page.getByLabel('Selection size',{exact:true})).toHaveValue('24px');
 await page.getByLabel('Selection font',{exact:true}).selectOption('Georgia');
 await expect(page.getByLabel('Selection font',{exact:true})).toHaveValue('Georgia');
 await editor.press('ControlOrMeta+a');
 await expect(page.getByLabel('Selection size',{exact:true})).toHaveValue('');
 await expect(page.getByLabel('Selection font',{exact:true})).toHaveValue('');
 await page.getByRole('button',{name:'Next match',exact:true}).click();
 await expect(page.getByLabel('Selection size',{exact:true})).toHaveValue('inherit');
 await page.getByRole('textbox',{name:'Replace with',exact:true}).fill('world');
 await page.getByRole('button',{name:'Replace current',exact:true}).click();await expect(editor.locator('p')).toHaveText('hello world');
 await page.getByRole('button',{name:'Replace all',exact:true}).click();await expect(editor.locator('p')).toHaveText('world world');
 await page.evaluate(()=>window.dispatchEvent(new CustomEvent('bibliarch-find',{detail:{query:'world'}})));
 await expect.poll(()=>page.evaluate(()=>getSelection()?.toString())).toBe('world');
 await page.getByRole('button',{name:'Undo',exact:true}).click();await expect(page.getByRole('button',{name:'Redo',exact:true})).toBeEnabled();
});
