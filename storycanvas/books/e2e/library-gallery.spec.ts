import {test, expect} from '@playwright/test';
const readLibrary=()=>new Promise<any>((resolve,reject)=>{const r=indexedDB.open('bibliarch-books',1);r.onsuccess=()=>{const db=r.result;const q=db.transaction('library').objectStore('library').get('bibliarch-books-v1');q.onsuccess=()=>{resolve(JSON.parse(q.result?.raw||'null'));db.close();};q.onerror=()=>{db.close();reject(q.error);};};r.onerror=()=>reject(r.error);});
test('home creates a truly blank book, searches saved books and reopens writing',async({page})=>{
 await page.goto('/books');
 await expect(page.getByRole('heading',{name:'Your books',exact:true})).toBeVisible();
 await page.getByRole('button',{name:'Create Blank book',exact:true}).click();
 await expect(page.getByRole('textbox',{name:'Manuscript'})).toHaveCount(1);
 await expect(page.getByRole('textbox',{name:'Manuscript'}).locator('p')).toHaveText('');
 await page.getByLabel('Book title',{exact:true}).fill('My untouched story');
 await page.getByRole('textbox',{name:'Manuscript'}).fill('Keep these exact words.');
 await page.getByRole('button',{name:'← My books',exact:true}).click();
 await page.getByRole('searchbox',{name:'Search books'}).fill('untouched');
 await expect(page.getByRole('button',{name:'Open My untouched story',exact:true})).toBeVisible();
 await page.reload();
 await expect(page.getByRole('heading',{name:'Your books',exact:true})).toBeVisible();
 await page.getByRole('button',{name:'Open My untouched story',exact:true}).click();
 await expect(page.getByRole('textbox',{name:'Manuscript'})).toContainText('Keep these exact words.');
});
test('visual presets and page gallery insert and restyle without replacing manuscript',async({page})=>{
 await page.goto('/books');
 await page.getByRole('button',{name:'Create Botanical journal',exact:true}).click();
 await expect(page.getByLabel('Book title',{exact:true})).toHaveValue('Botanical journal');
 const ed=page.getByRole('textbox',{name:'Manuscript'}).first();
 await ed.fill('A very personal opening.');
 await page.getByRole('button',{name:'Page templates',exact:true}).click();
 const gallery=page.getByRole('dialog',{name:'Page template gallery'});
 await gallery.getByRole('button',{name:'Choose Chapter opener',exact:true}).click();
 await gallery.getByRole('button',{name:'Choose Ornate style',exact:true}).click();
 await gallery.getByRole('button',{name:'Change this page',exact:true}).click();
 await expect(ed).toContainText('A very personal opening.');
 await expect.poll(async()=>{const l=await page.evaluate(readLibrary);return l?.books.find((b:any)=>b.id===l.activeBook).chapters[0].scenes[0].layout.border}).toBe('double');
 await gallery.getByRole('button',{name:'Choose Illustration',exact:true}).click();
 await gallery.getByRole('button',{name:'Add as new page',exact:true}).click();
 await expect(gallery).not.toBeVisible();
 await expect.poll(async()=>{const l=await page.evaluate(readLibrary);return l?.books.find((b:any)=>b.id===l.activeBook).chapters[0].scenes.map((s:any)=>s.template)}).toEqual(['chapter-title','color-art']);
 await page.getByRole('button',{name:'← My books',exact:true}).click();
 await page.getByRole('button',{name:'Open Botanical journal',exact:true}).click();
 await expect(page.getByRole('textbox',{name:'Manuscript'}).first()).toContainText('A very personal opening.');
});
